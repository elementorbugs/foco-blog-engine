// Self-hosts the Google Fonts the site uses, so visitors' IPs are never sent to Google (GDPR, LG Munich 2022).
// 1. fetches each Google css2 URL the site loads, keeps the latin + latin-ext woff2 files
// 2. uploads them to the WP media library (fonts-local/media-map.json remembers them)
// 3. generates homepage-backup/self-hosted-fonts-snippet.php and deploys it as a Code Snippet: it prints the
//    @font-face rules and strips every fonts.googleapis.com / fonts.gstatic.com reference from the HTML.
//   node deploy-self-hosted-fonts.js          everything
//   node deploy-self-hosted-fonts.js --build  only download + regenerate the snippet file (no network to WP)
// New Google font on the site? Add its css2 URL to SOURCES and re-run. Rollback: deactivate "FOCO self-hosted fonts".
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const env = {};
fs.readFileSync(path.join(__dirname, '.env'), 'utf8').split(/\r?\n/).forEach(l => {
  if (!l || l.trim().startsWith('#')) return;
  const i = l.indexOf('=');
  if (i > 0) env[l.slice(0, i).trim()] = l.slice(i + 1).trim();
});
const BASE = 'https://' + env.WP_HOST.replace(/^https?:\/\//, '').replace(/\/$/, '');
const AUTH = 'Basic ' + Buffer.from(env.WP_USER + ':' + env.WP_APP_PASSWORD).toString('base64');
const BUILD_ONLY = process.argv.includes('--build');
const DIR = path.join(__dirname, 'fonts-local');
const MAP_FILE = path.join(DIR, 'media-map.json');
const SNIPPET_FILE = path.join(__dirname, 'homepage-backup', 'self-hosted-fonts-snippet.php');
const NAME = 'FOCO self-hosted fonts (2026-10-28)';
const KEEP = ['latin', 'latin-ext'];
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

// Every Google Fonts stylesheet found on the live site (2026-10-28 sweep of all sitemap URLs).
const SOURCES = [
  'https://fonts.googleapis.com/css2?family=Lexend:wght@400;500;600;700;800&family=Plus+Jakarta+Sans:wght@400;500;600;700;800&display=swap',
  'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800;900&display=swap',
  'https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,400..700;1,9..144,400..600&family=Figtree:wght@400;500;600;700&display=swap',
];

const wp = async (method, url, body, headers = {}) => {
  const r = await fetch(BASE + url, { method, headers: { Authorization: AUTH, ...headers }, body });
  const text = await r.text();
  let json = null; try { json = JSON.parse(text); } catch (e) { /* not json */ }
  return { status: r.status, json, text };
};

function snippetCode(css) {
  return `<?php
/**
 * FOCO self-hosted fonts (2026-10-28). GENERATED by deploy-self-hosted-fonts.js, do not edit by hand.
 * Serves Lexend, Plus Jakarta Sans, Inter, Fraunces and Figtree from the media library instead of Google, so
 * no visitor IP goes to Google before consent. Prints the @font-face rules at the top of <head> and strips
 * every fonts.googleapis.com / fonts.gstatic.com link, preconnect and @import from the page, including the
 * standalone room and timer pages (the buffer starts before they echo and exit).
 * Rollback: deactivate this snippet.
 */
add_filter( 'upload_mimes', function ( $m ) { $m['woff2'] = 'font/woff2'; return $m; } );
add_filter( 'wp_check_filetype_and_ext', function ( $data, $file, $filename ) {
	if ( preg_match( '/\\.woff2$/i', $filename ) ) { return array( 'ext' => 'woff2', 'type' => 'font/woff2', 'proper_filename' => false ); }
	return $data;
}, 10, 3 );

function foco_fonts_css() {
	return <<<'FOCOFONTS'
${css}
FOCOFONTS;
}

add_action( 'template_redirect', function () {
	if ( is_admin() || wp_doing_ajax() || is_feed() || '' === trim( foco_fonts_css() ) ) { return; }
	ob_start( function ( $html ) {
		if ( false === stripos( $html, '<head' ) ) { return $html; }
		$html = preg_replace( '#<link\\b[^>]*fonts\\.(googleapis|gstatic)\\.com[^>]*>\\s*#i', '', $html );
		$html = preg_replace( '#@import\\s+url\\(\\s*[\\'"]?https?://fonts\\.googleapis\\.com[^)]*\\)\\s*;?#i', '', $html );
		return preg_replace( '#<head\\b[^>]*>#i', '$0<style id="foco-fonts">' . foco_fonts_css() . '</style>', $html, 1 );
	} );
}, 0 );
`;
}

(async () => {
  fs.mkdirSync(DIR, { recursive: true });
  const map = fs.existsSync(MAP_FILE) ? JSON.parse(fs.readFileSync(MAP_FILE, 'utf8')) : {};

  // 1. Google's CSS -> latin + latin-ext faces
  const faces = [];
  for (const src of SOURCES) {
    const css = await (await fetch(src, { headers: { 'User-Agent': UA } })).text();
    for (const m of css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)) {
      if (!KEEP.includes(m[1])) continue;
      const url = m[2].match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/)[1];
      const family = m[2].match(/font-family:\s*'([^']+)'/)[1];
      faces.push({ subset: m[1], family, url, rule: m[2] });
    }
  }
  if (!faces.length) throw new Error('no @font-face rules parsed: Google changed its CSS format?');

  // 2. download (deduped: variable fonts share one file across weights)
  const files = {};
  for (const f of faces) {
    if (files[f.url]) continue;
    const name = `${f.family.toLowerCase().replace(/\s+/g, '-')}-${f.subset}-${crypto.createHash('md5').update(f.url).digest('hex').slice(0, 8)}.woff2`;
    const local = path.join(DIR, name);
    if (!fs.existsSync(local)) fs.writeFileSync(local, Buffer.from(await (await fetch(f.url)).arrayBuffer()));
    files[f.url] = name;
  }
  console.log(`${faces.length} @font-face rules, ${Object.keys(files).length} woff2 files, ${Math.round(Object.values(files).reduce((s, n) => s + fs.statSync(path.join(DIR, n)).size, 0) / 1024)} KB`);

  const build = () => faces.map(f => map[files[f.url]] ? f.rule.replace(f.url, map[files[f.url]]) : null);
  const writeSnippet = rules => fs.writeFileSync(SNIPPET_FILE, snippetCode(rules.every(Boolean) ? rules.join('').replace(/\s*\n\s*/g, '') : ''));

  const deploy = async () => {
    const list = (await wp('GET', '/wp-json/code-snippets/v1/snippets')).json;
    const existing = list.find(s => s.name.startsWith('FOCO self-hosted fonts'));
    const body = JSON.stringify({ name: NAME, desc: 'Google Fonts served from the media library; strips Google font links. Generated by deploy-self-hosted-fonts.js.', scope: 'global', active: true, code: fs.readFileSync(SNIPPET_FILE, 'utf8').replace(/^<\?php\s*/, '') });
    const r = await wp(existing ? 'PUT' : 'POST', '/wp-json/code-snippets/v1/snippets' + (existing ? '/' + existing.id : ''), body, { 'Content-Type': 'application/json' });
    console.log(`snippet: HTTP ${r.status} | id ${r.json && r.json.id} | active ${r.json && r.json.active} | code_error ${JSON.stringify(r.json && r.json.code_error)}`);
    if (r.status >= 300 || (r.json && r.json.code_error)) throw new Error('snippet deploy failed');
  };

  writeSnippet(build());
  if (BUILD_ONLY) { console.log('built', SNIPPET_FILE); return; }

  // 3. phase 1: snippet that only allows woff2 uploads (empty CSS = no stripping), then upload missing files
  const missing = Object.values(files).filter(n => !map[n]);
  if (missing.length) {
    writeSnippet([null]);
    await deploy();
    for (const n of missing) {
      const r = await wp('POST', '/wp-json/wp/v2/media', fs.readFileSync(path.join(DIR, n)), { 'Content-Type': 'font/woff2', 'Content-Disposition': `attachment; filename="${n}"` });
      if (r.status >= 300) throw new Error(`upload ${n} failed: ${r.status} ${r.text.slice(0, 200)}`);
      map[n] = r.json.source_url.replace(/^https?:\/\/[^/]+/, '');
      fs.writeFileSync(MAP_FILE, JSON.stringify(map, null, 2));
      console.log('uploaded', n);
    }
  }
  // check every file is served as a font before switching pages over
  for (const n of Object.values(files)) {
    const r = await fetch(BASE + map[n], { method: 'HEAD' });
    if (r.status !== 200) throw new Error(`${map[n]} returned ${r.status}`);
  }

  // 4. phase 2: the real snippet
  writeSnippet(build());
  await deploy();
})();
