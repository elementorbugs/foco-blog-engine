// Builds homepage-backup/light-pages-snippet.php: light theme for regular WP pages (2026-10-09).
// Reuses light-articles.css (the posts' light rules) scoped to body.foco-light-page, plus the
// post layout (left-aligned 860px column under the 1200px header container).
// Usage: node scripts/build-light-pages-snippet.js   then upload the .php as Code Snippet #12.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
let css = fs.readFileSync(path.join(root, 'light-articles.css'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\.single-post \.foco-nav[^\n]*\n/m, '')
  .replace(/\.blog-single/g, '.foco-light-page .blog-single')
  .replace(/\s*\n\s*/g, ' ').replace(/\s*([{};,])\s*/g, '$1').trim();
const P = '.foco-light-page .blog-single';
const extra = [
  'html:has(body.foco-light-page),body.foco-light-page .foco-app{background:#FAF8FD !important}',
  `${P}{padding-top:118px !important}`,
  `${P} .wrap{max-width:1200px !important;padding-left:24px !important;padding-right:24px !important;margin-left:auto !important;margin-right:auto !important}`,
  `${P} .wrap>*{max-width:860px !important;margin-left:0 !important;margin-right:0 !important}`,
  `${P} article,${P} article>*{text-align:left !important}`,
  `${P} article figure,${P} article .wp-block-image,${P} article .foco-img{margin-left:0 !important;margin-right:auto !important}`,
  `${P} article p,${P} article li{color:#4A4560 !important;font-size:18px !important;line-height:1.85 !important;letter-spacing:.015em !important}`,
  `${P} article strong{color:#2A2340 !important;font-weight:600 !important}`,
  `${P} h1,${P} article h2,${P} article h3,${P} article h4{font-weight:600 !important;letter-spacing:.005em !important;color:#2A2340 !important}`,
  `${P} h1{font-size:clamp(32px,4vw,48px) !important;line-height:1.2 !important}`,
  `${P} article h2{font-size:clamp(24px,2.4vw,29px) !important;line-height:1.3 !important;margin-top:52px !important;margin-bottom:14px !important}`,
  `${P} article h3{font-size:21px !important;line-height:1.35 !important;margin-top:32px !important}`,
  `${P} article hr,${P} article .wp-block-separator{border:0 !important;border-top:1px solid #E7E0F5 !important;background:none !important;opacity:1 !important;margin:40px 0 !important;height:0 !important}`,
  `${P} .foco-tldr{background:#F3EEFC !important;border:0 !important;border-left:4px solid #7C3AED !important;border-radius:14px !important;box-shadow:none !important;padding:22px 26px !important}`,
  `${P} article .foco-tldr,${P} article .foco-tldr *{color:#2A2340 !important}`,
  `${P} article .foco-tldr a{color:#5B21B6 !important}`,
  `${P} .foco-tldr strong,${P} article .foco-tldr strong{color:#2A2340 !important}`,
  // inline accent colours written for the old dark pages (e.g. /features/ cards): lilac and orange
  // text is 2.1-2.6:1 on the light page, so darken them; dark islands keep the originals
  `${P} article [style*="color:#A78BFA"]{color:#5B21B6 !important}`,
  `${P} article [style*="color:#FB923C"]{color:#B4400C !important}`,
  `${P} article .foco-dark [style*="color:#A78BFA"],${P} article .foco-bd-dump-tool [style*="color:#A78BFA"],${P} article [class*="foco-chart"] [style*="color:#A78BFA"]{color:#A78BFA !important}`,
  `${P} article .foco-dark [style*="color:#FB923C"],${P} article .foco-bd-dump-tool [style*="color:#FB923C"],${P} article [class*="foco-chart"] [style*="color:#FB923C"]{color:#FB923C !important}`,
  `${P} article a[style*="background:rgba(124,58,237,0.08)"]{color:#2A2340 !important;background:#FFFFFF !important;border-color:#ECE6F7 !important}`,
  `${P} article a[style*="background:rgba(251,146,60,0.08)"]{color:#2A2340 !important}`,
  `${P} article [style*="font-size:36px"],${P} article [style*="font-size:32px"]{color:#2A2340 !important}`,
  `${P} .foco-key-takeaways{background:#fff !important;border:1px solid #ECE6F7 !important;border-radius:16px !important}`,
  `${P} .foco-key-takeaways h2{font-size:18px !important;margin-top:0 !important;color:#5B21B6 !important}`,
  `${P} article blockquote,${P} article .wp-block-quote{border-left:4px solid #A78BFA !important;background:#F6F2FD !important;border-radius:0 12px 12px 0 !important;padding:16px 22px !important}`,
  `@media (max-width:640px){${P}{padding-top:100px !important}${P} article p,${P} article li{font-size:17px !important;line-height:1.8 !important}}`,
].join('');
const EXCLUDE = [17, 1138, 4809]; // classic homepage, Free ADHD Tools (step 3), homepage draft
const php = `<?php
/**
 * FOCO light pages (2026-10-09). Runs as a "Code Snippets" plugin snippet. GENERATED by
 * scripts/build-light-pages-snippet.js from light-articles.css: edit those, then rebuild.
 *
 * Brand rule: every page is light; dark is only an accent. Adds body class foco-light-page to
 * regular pages (not the front page; not ids ${EXCLUDE.join(', ')}) and applies the posts' light
 * rules to them, including the dark-island rules that keep embedded tools readable.
 * Rollback: deactivate this snippet.
 */
add_filter( 'body_class', function ( $classes ) {
	if ( is_page() && ! is_front_page() && ! in_array( get_queried_object_id(), array( ${EXCLUDE.join(', ')} ), true ) ) {
		$classes[] = 'foco-light-page';
	}
	return $classes;
} );

add_action( 'wp_head', function () {
	if ( ! is_page() || is_front_page() || in_array( get_queried_object_id(), array( ${EXCLUDE.join(', ')} ), true ) ) {
		return;
	}
	echo '<style id="foco-light-pages">' . ${JSON.stringify(css + extra)} . '</style>'; // phpcs:ignore WordPress.Security.EscapeOutput -- static CSS
}, 100 );
`;
fs.writeFileSync(path.join(root, 'homepage-backup', 'light-pages-snippet.php'), php);
console.log('css', (css + extra).length, 'chars');
